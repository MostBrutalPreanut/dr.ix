import type { Checklist, ChecklistGroup } from '../lib/types';

/** Builds a group with stable ids (`<prefix>-<n>`) so the seed is idempotent on every device. */
function group(prefix: string, title: string, items: Array<string | [text: string, detail: string]>): ChecklistGroup {
  return {
    id: prefix,
    title,
    items: items.map((it, i) => {
      const [text, detail] = Array.isArray(it) ? it : [it, undefined];
      return { id: `${prefix}-${i + 1}`, text, ...(detail ? { detail } : {}) };
    }),
  };
}

